import { DeeperError, KEY_STORAGE, deeperRead, describeDeeperError } from '../ai/gemini';
import { announce, h } from './dom';

function readKey(): string {
  try {
    return sessionStorage.getItem(KEY_STORAGE) ?? '';
  } catch {
    return '';
  }
}
function writeKey(value: string): void {
  try {
    if (value) sessionStorage.setItem(KEY_STORAGE, value);
    else sessionStorage.removeItem(KEY_STORAGE);
  } catch {
    /* storage unavailable: the key lives only in the input for this view */
  }
}

/** The optional BYOK panel, shown in a dialog. */
export function createDeeperDialog(leaseText: () => string): HTMLDialogElement {
  const keyInput = h('input', {
    id: 'gemini-key',
    type: 'password',
    autocomplete: 'off',
    spellcheck: 'false',
    placeholder: 'Paste your Gemini API key',
  });
  keyInput.value = readKey();
  const runButton = h('button', { class: 'btn btn-primary', type: 'button' }, 'Run deeper read');
  const forgetButton = h('button', { class: 'btn btn-quiet', type: 'button' }, 'Forget key');
  const status = h('p', { class: 'small', role: 'status', 'aria-live': 'polite' });
  const output = h('div', { class: 'deeper-output', hidden: true });
  const close = h('button', { class: 'btn btn-quiet dialog-close', type: 'button', 'aria-label': 'Close deeper read' }, 'Close');

  const dialog = h(
    'dialog',
    { class: 'sheet', 'aria-labelledby': 'deeper-title' },
    h(
      'div',
      { class: 'sheet-head' },
      h('h2', { id: 'deeper-title' }, 'Deeper read'),
      close,
    ),
    h('p', {}, 'Optional. LeaseLens already works without this. A deeper read asks Google’s Gemini model for a short plain-English summary to sit beside the checks above.'),
    h(
      'div',
      { class: 'notice' },
      h('strong', {}, 'What gets sent'),
      h(
        'p',
        { class: 'small' },
        'Only when you press the button below, the full lease text and your key go straight from this browser to Google’s Gemini API. Nothing goes to LeaseLens or anyone else, because there is no LeaseLens server. Your key is kept in this tab’s session storage and disappears when you close the tab.',
      ),
    ),
    h('label', { for: 'gemini-key' }, 'Your Gemini API key'),
    h('p', { class: 'small' }, 'Get one for free in Google AI Studio (aistudio.google.com).'),
    keyInput,
    h('div', { class: 'row' }, runButton, forgetButton),
    status,
    output,
  );

  close.addEventListener('click', () => dialog.close());
  forgetButton.addEventListener('click', () => {
    keyInput.value = '';
    writeKey('');
    status.textContent = 'Key forgotten.';
    announce('Key forgotten');
  });
  runButton.addEventListener('click', async () => {
    const key = keyInput.value.trim();
    if (!key) {
      status.textContent = 'Paste a key first.';
      keyInput.focus();
      return;
    }
    writeKey(key);
    runButton.disabled = true;
    output.hidden = true;
    status.textContent = 'Reading the lease with Gemini. This usually takes a few seconds.';
    try {
      const text = await deeperRead(key, leaseText());
      output.replaceChildren(h('h3', {}, 'Summary from Gemini'), ...text.split(/\n{2,}|\n(?=\d\.)/).map((p) => h('p', {}, p.trim())), h('p', { class: 'small' }, 'Generated by an AI model. It can be wrong. This is not legal advice.'));
      output.hidden = false;
      status.textContent = 'Done.';
    } catch (err) {
      const code = err instanceof DeeperError ? err.code : 'unknown';
      status.textContent = describeDeeperError(code);
    } finally {
      runButton.disabled = false;
    }
  });
  return dialog;
}
